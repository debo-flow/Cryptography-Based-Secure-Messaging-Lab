"""
Automated Testing for Milestone 14: PBE & KDF Integrations.
"""
import pytest
import json
from core.pbe import encrypt_with_password, decrypt_with_password, migrate_pbe_package
from core.kdf_engine import KDF_REGISTRY
from core.exceptions import InvalidInputError, AuthenticationError

@pytest.mark.parametrize("kdf_algo", ["PBKDF2-HMAC-SHA256", "Scrypt", "Argon2id"])
def test_pbe_matrix_round_trip(kdf_algo):
    """Tests full encryption/decryption cycle across all supported KDFs using default parameters."""
    password = "StrongPassword456"
    message = f"Highly confidential PBE payload using {kdf_algo} 🔐"
    
    payload = encrypt_with_password(password, message, kdf_algo=kdf_algo)
    
    assert payload["format_version"] == "1.1"
    assert payload["encryption_type"] == "Password-Based Encryption"
    assert payload["kdf"]["algorithm"] == kdf_algo
    
    recovered = decrypt_with_password(password, json.dumps(payload))
    assert recovered == message

def test_pbe_v1_0_backward_compatibility():
    """Simulates a package generated by the older M13 engine and ensures M14 can decrypt it."""
    v1_0_package = {
        "format_version": "1.0",
        "encryption_type": "Password-Based Encryption",
        "kdf": {
            "algorithm": "PBKDF2",
            "prf": "HMAC-SHA256",
            "iterations": 50000, 
            "salt": "Yk2d8e3vT3uYx+1t8s+f7A=="
        },
        "cipher": {
            "algorithm": "AES-256-GCM",
            "nonce": "mG8M8G1z/g5g8m1x"
        },
        "aad": "",
        # This ciphertext/tag was generated specifically for the password "RetroTest" and the hardcoded salt/nonce above
        "ciphertext": "Tbz992POnCg8bBfA68uIq88rT7aT3tEwP/p+s/q2"
    }
    
    # Should safely reconstruct M13 AAD string internally and authenticate
    recovered = decrypt_with_password("RetroTest", json.dumps(v1_0_package))
    assert recovered == "Legacy Data"
    
def test_pbe_migration_system():
    """Tests the safe upgrade workflow from an old PBKDF2 package to an Argon2id package."""
    password = "MigrationUser"
    
    # 1. Create a PBKDF2 payload
    old_payload = encrypt_with_password(password, "Critical Data", "PBKDF2-HMAC-SHA256")
    
    # 2. Migrate it directly to Argon2id
    new_payload = migrate_pbe_package(password, json.dumps(old_payload), "Argon2id")
    
    assert new_payload["kdf"]["algorithm"] == "Argon2id"
    assert decrypt_with_password(password, json.dumps(new_payload)) == "Critical Data"

def test_pbe_wrong_password_rejection():
    payload = encrypt_with_password("CorrectPass", "Data", "Argon2id")
    with pytest.raises(AuthenticationError):
        decrypt_with_password("WrongPass", json.dumps(payload))
